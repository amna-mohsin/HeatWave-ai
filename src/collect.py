"""Download raw data from both public sources and write DATA_SOURCES.md with the REAL download time.
Run:  python -m src.collect"""
import io, json, time
from datetime import datetime, timezone
import pandas as pd
import requests
from .config import RAW_DIR, ROOT, START_DATE, END_DATE, GSOD_STATION, LAT, LON
from .weather_api import fetch_archive

GSOD_URL = "https://www.ncei.noaa.gov/data/global-summary-of-the-day/access/{year}/{station}.csv"


def collect_open_meteo():
    frames, years = [], range(int(START_DATE[:4]), int(END_DATE[:4]) + 1)
    for y0 in range(years.start, years.stop, 5):                  # 5-year chunks
        y1 = min(y0 + 4, years.stop - 1)
        s = max(f"{y0}-01-01", START_DATE); e = min(f"{y1}-12-31", END_DATE)
        print(f"Open-Meteo ERA5 {s} -> {e}")
        frames.append(fetch_archive(s, e)); time.sleep(3)
    df = pd.concat(frames).drop_duplicates("date").sort_values("date")
    df.to_csv(RAW_DIR / "open_meteo.csv", index=False)
    return df


def collect_noaa():
    frames = []
    for y in range(int(START_DATE[:4]), int(END_DATE[:4]) + 1):
        r = requests.get(GSOD_URL.format(year=y, station=GSOD_STATION), timeout=60)
        if r.status_code != 200:
            print(f"  GSOD {y}: not available (HTTP {r.status_code})"); continue
        frames.append(pd.read_csv(io.StringIO(r.text)))
        print(f"  GSOD {y}: {len(frames[-1])} rows")
    df = pd.concat(frames, ignore_index=True)
    df.to_csv(RAW_DIR / "noaa_gsod.csv", index=False)
    return df


def write_docs(om, noaa, stamp):
    meta = {"downloaded_utc": stamp, "open_meteo_rows": len(om), "noaa_rows": len(noaa),
            "period_requested": [START_DATE, END_DATE], "station": GSOD_STATION}
    (RAW_DIR / "collection_metadata.json").write_text(json.dumps(meta, indent=2))
    md = f"""# Data Sources (auto-generated by `python -m src.collect`)

| Detail | Open-Meteo (ERA5) | NOAA GSOD |
|---|---|---|
| Dataset | ERA5 reanalysis via Open-Meteo Historical Weather API | Global Summary of the Day |
| Role in project | **Input features** (daily weather) | **Target labels** (station heat index) |
| Collection method | REST API, 5-year chunks, `models=era5`, timezone Asia/Karachi | HTTP download of yearly CSV, station {GSOD_STATION} |
| URL | https://open-meteo.com/en/docs/historical-weather-api | https://www.ncei.noaa.gov/data/global-summary-of-the-day/access/ |
| Licence | CC BY 4.0 (attribution: Open-Meteo.com, Copernicus ERA5) | NOAA open data; cite NOAA NCEI (see WMO Resolution 40 caveat below) |
| Location | Grid cell at {LAT}, {LON} (Karachi) | Karachi Jinnah Intl Airport |
| Rows downloaded | {len(om):,} | {len(noaa):,} |
| Requested period | {START_DATE} to {END_DATE} | {START_DATE} to {END_DATE} |
| **Download date (UTC)** | **{stamp}** | **{stamp}** |

No personal identifiers are present in either dataset.

## How to cite / credit
* Open-Meteo: "Weather data by Open-Meteo.com" (https://open-meteo.com/), licence CC BY 4.0
  (https://creativecommons.org/licenses/by/4.0/). Underlying data: ERA5 - Hersbach et al. (2020), Copernicus Climate Change Service.
  Open-Meteo's free API is for non-commercial use (this is an educational project).
* NOAA: NOAA National Centers for Environmental Information. 1999. Global Surface Summary of the Day - GSOD. 1.0.
  [Karachi Jinnah Intl Airport, station {GSOD_STATION}]. NOAA NCEI. Accessed {stamp[:10]}.
  NOAA gives no warranty on accuracy. NCEI notes that some international *commercial* use of data may be subject to WMO Resolution 40; not relevant to this educational use.

## Notes
* ERA5 is a gridded reanalysis (~25 km); GSOD is a single airport station. They are different
  products, so their values differ. This is discussed in the report's limitations.
* Station labels: daily heat index computed from GSOD max temperature and mean dew point
  (NWS Rothfusz equation). See `src/heat.py`.
"""
    (ROOT / "data" / "DATA_SOURCES.md").write_text(md)


if __name__ == "__main__":
    RAW_DIR.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M")
    om = collect_open_meteo(); noaa = collect_noaa()
    write_docs(om, noaa, stamp)
    print("Done. Raw files saved in data/raw/. DATA_SOURCES.md written.")
